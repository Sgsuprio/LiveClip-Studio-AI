#!/usr/bin/env python3
"""Build clip.py — the standalone LiveClip pipeline for GitHub Actions.

Single source of truth is build_notebook.py: the pipeline stages (config,
ingest, transcribe, score, render, package) are its CELL_* constants. This
generator embeds them in clip.py, which runs them in order with the
"/content/liveclip" paths replaced by a --workdir at runtime (the same trick
the VM test harness uses), writes run_status.json, and copies the results
into --outdir for the workflow to publish.

Run: python3 build_clip.py
Writes clip.py in the same directory.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_notebook as bn

CELLS = [
    bn.CELL_CONFIG,
    bn.CELL_INGEST,
    bn.CELL_TRANSCRIBE,
    bn.CELL_SCORE,
    bn.CELL_RENDER,
    bn.CELL_PACKAGE,
]

HEADER = '''#!/usr/bin/env python3
"""LiveClip pipeline as a standalone script (GitHub Actions backend).

GENERATED by build_clip.py from build_notebook.py — do not edit by hand.
Edit the CELL_* stages in build_notebook.py and re-run build_clip.py.

Usage:
  python3 clip.py --config liveclip_config.json --workdir liveclip-work \\
      --outdir results/latest

Reads the flat v2 config, runs ingest -> transcribe -> score -> render ->
package, writes run_status.json (running/done/error) plus liveclip_clips.json,
clip MP4s/SRTs and the export ZIP into --outdir. The workflow publishes
--outdir to the orphan `results` branch, and the Studio page loads it back
with no file download or upload.
"""
import argparse
import datetime
import glob
import json
import os
import shutil
import sys


def write_status(outdir, status, source_url="", message="", clips=0):
    payload = {
        "status": status,
        "source_url": source_url,
        "updated_at": datetime.datetime.now(datetime.timezone.utc).isoformat().replace("+00:00", "Z"),
        "clips": clips,
        "message": message,
    }
    with open(os.path.join(outdir, "run_status.json"), "w") as f:
        json.dump(payload, f, indent=2)
    print(f"[status] {status}: {message or source_url}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True, help="flat v2 liveclip_config.json")
    ap.add_argument("--workdir", default="liveclip-work")
    ap.add_argument("--outdir", default="results/latest")
    args = ap.parse_args()

    workdir = os.path.abspath(args.workdir)
    outdir = os.path.abspath(args.outdir)
    os.makedirs(workdir, exist_ok=True)
    os.makedirs(outdir, exist_ok=True)

    with open(args.config) as f:
        cfg = json.load(f)
    source_url = cfg.get("source_url", "")
    # The config cell picks up liveclip_config.json from the current directory,
    # so run the stages with the workdir as CWD (like Colab's /content).
    shutil.copy(args.config, os.path.join(workdir, "liveclip_config.json"))
    os.chdir(workdir)

    started = datetime.datetime.now(datetime.timezone.utc)
    write_status(outdir, "running", source_url, "Clipping started — downloading and transcribing.")
    ns = {"__name__": "__main__"}
    try:
        for i, src in enumerate(CELLS):
            print(f"\\n===== stage {i + 1}/{len(CELLS)} =====", flush=True)
            exec(compile(src.replace("/content/liveclip", workdir), f"<stage {i + 1}>", "exec"), ns)
    except Exception as e:
        write_status(outdir, "error", source_url, f"{type(e).__name__}: {e}")
        raise

    # Package cell wrote everything into the workdir — publish it.
    results_path = os.path.join(workdir, "liveclip_clips.json")
    results = json.load(open(results_path))
    results["backend"] = "github-actions"
    results["run_started_at"] = started.isoformat().replace("+00:00", "Z")
    with open(results_path, "w") as f:
        json.dump(results, f, indent=2)
    for name in ["liveclip_clips.json", "LiveClip_Export_Pack.zip", "config.json"]:
        src = os.path.join(workdir, name)
        if os.path.exists(src):
            shutil.copy(src, os.path.join(outdir, name))
    for mp4 in sorted(glob.glob(os.path.join(workdir, "clip*.mp4"))):
        shutil.copy(mp4, outdir)
    for srt in sorted(glob.glob(os.path.join(workdir, "clip*.srt"))):
        shutil.copy(srt, outdir)
    n = len(results.get("clips", []))
    if n == 0:
        write_status(outdir, "error", source_url, "No clips found — the video may have too little speech in this segment.")
    else:
        write_status(outdir, "done", source_url, f"{n} clip(s) ready.", clips=n)
    print(f"\\nDone: {n} clip(s) in {outdir}")


# Pipeline stages (from build_notebook.py — do not edit here).
CELLS = '''


def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "clip.py")
    with open(out, "w") as f:
        f.write(HEADER)
        f.write(repr(CELLS))
        f.write('\n\n\nif __name__ == "__main__":\n    main()\n')
    print(f"wrote {out}")
    # validate: the generated script must compile
    src = open(out).read()
    compile(src, "clip.py", "exec")
    print(f"validated: {len(CELLS)} stages, clip.py compiles")


if __name__ == "__main__":
    main()
